describe("the era predicate itself", () => {
  it("dates every cast off committed fixtures", () => {
    // [session 89] 148 -> 168: session 87's twenty-cast batch.
    expect(traces.length).toBe(178);  /* [session 91] was 168 */
    expect(created.size).toBe(178);  /* [session 91] was 168 */
    for (const t of traces) expect(created.has(t.docId)).toBe(true);
  });

  it("splits 94 preOil / 62 oilSupplied / 22 focusDry — THREE eras, because the middle one ran out of Focus Oil", () => {
    // [session 92, §32 ANSWERED — option (b)] The two-era model pooled
    // `oilSupplied` with `focusDry`, and that pooling is what made four claims
    // in this file degrade across three batches. `preOil` is unchanged at 94;
    // the old 84-cast `today` arm splits 62/22 here.
    expect(POLICY_ERA_BOUNDARY).toBe("2026-08-21");
    expect(FOCUS_DRY_BOUNDARY).toBe("2026-08-24T00:02:57.148Z");
    expect(split.preOil.length).toBe(94);
    expect(split.oilSupplied.length).toBe(62);
    expect(split.focusDry.length).toBe(22);
    expect(split.preOil.length + split.oilSupplied.length + split.focusDry.length).toBe(traces.length);
  });

  it("cuts the second boundary INSIDE a single batch, which is why it is a timestamp and not a date", () => {
    // [session 92] The 2026-08-24T00:01:04 -> 00:05:48 batch straddles the
    // Focus-Oil exhaustion: 8 casts still had stock, 12 did not. A day-precision
    // predicate puts all 20 on the same side and cannot express this at all.
    const batch = traces.filter((t) => {
      const at = created.get(t.docId)!;
      return at >= "2026-08-24T00:00:00.000Z" && at < "2026-08-24T01:00:00.000Z";
    });
    expect(batch.length).toBe(20);
    const supplied = batch.filter((t) => eraOf(t.docId, created) === "oilSupplied");
    const dry = batch.filter((t) => eraOf(t.docId, created) === "focusDry");
    expect([supplied.length, dry.length]).toEqual([8, 12]);
    // And the day-precision answer really is degenerate — the thing being ruled out.
    expect(new Set(batch.map((t) => created.get(t.docId)!.slice(0, 10))).size).toBe(1);
  });

  it("keeps `focusDry` a REVERSION rather than a new regime — it lands between the other two, nearer preOil", () => {
    // [session 92] This is the claim the whole re-specification rests on: the
    // policy did not change at the second boundary, the CONSUMABLE ran out. So
    // focusDry must look like preOil, not like a third behaviour.
    const f = focusEraSplit(traces, created);
    expect(f.focusDry.rate).toBeGreaterThan(f.oilSupplied.rate * 10);
    expect(f.focusDry.rate).toBeLessThan(f.preOil.rate);
    // Deck-controlled, so a base-deck confound cannot be the explanation:
    // rod-dealt only, oilSupplied 3/215 against focusDry 19/52.
    const rod = (ts: readonly CastTrace[]) => ts.filter((t) => traceDealtDeck(t) === "rod");
    const rate = (ts: readonly CastTrace[]) => {
      const plays = ts.reduce((a, t) => a + playCount(t), 0);
      return ts.reduce((a, t) => a + budgetZeroPlays(t), 0) / plays;
    };
    expect(rate(rod(split.oilSupplied))).toBeCloseTo(0.014, 3);
    expect(rate(rod(split.focusDry))).toBeCloseTo(0.365, 3);
    expect(rate(rod(split.focusDry)) / rate(rod(split.oilSupplied))).toBeGreaterThan(20);
  });

  it("passes its own soundness assertions", () => {
    expect(() => assertCastEraSound(traces, created)).not.toThrow();
  });

  it("refuses to default an undated cast rather than binning it as 'before'", () => {
    expect(() => eraOf("nope", new Map())).toThrow(/no doc.createdAt/);
  });

  it("holds focusMeterMax at FOCUS_POOL on every turn of both eras, which the counterfactual depends on", () => {
    expect(FOCUS_POOL).toBe(3);
    for (const t of traces) for (const turn of t.turns) expect(turn.focusMeterMax).toBe(FOCUS_POOL);
  });

  it("has its FIRST boundary bracketed by a 20-hour gap, so that date literal does not matter", () => {
    const stamps = [...created.values()].sort();
    const lastBefore = stamps.filter((s) => s.slice(0, 10) < POLICY_ERA_BOUNDARY).at(-1);
    const firstToday = stamps.find((s) => s.slice(0, 10) >= POLICY_ERA_BOUNDARY);
    expect(lastBefore).toBe("2026-08-20T18:28:24.964Z");
    expect(firstToday).toBe("2026-08-21T14:46:17.309Z");
  });
});

