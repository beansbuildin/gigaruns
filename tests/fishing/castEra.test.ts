    // CAUSE IS NAMED. This bound read `> 28` in session 84/86, was cut to
    // `> 3` across sessions 89 and 91 as the ratio went ~30x -> 6.48x -> 3.92x,
    // and each session read that as its claim dying. **It was not dying; it was
