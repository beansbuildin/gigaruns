    const before = redrawCounterfactual(split.preOil);
    const supplied = redrawCounterfactual(split.oilSupplied);
    const dry = redrawCounterfactual(split.focusDry);
    const pooled = redrawCounterfactual(traces);
    // The arms partition the pooled table, so this is a real partition check
